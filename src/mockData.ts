export function generateTenantDailyTrends(baseViews: number, baseOrders: number, avgSpend: number): DailyTrend[] {
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  const dates = [
    'Sep 08', 'Sep 09', 'Sep 10', 'Sep 11', 'Sep 12', 'Sep 13', 'Sep 14',
    'Sep 15', 'Sep 16', 'Sep 17', 'Sep 18', 'Sep 19', 'Sep 20', 'Sep 21'
  ];

  // Daily multipliers to create realistic weekend spikes
  const multipliers = [0.75, 0.82, 0.90, 0.95, 1.35, 1.65, 1.50, 0.78, 0.85, 0.92, 1.05, 1.40, 1.70, 1.55];

  return dates.map((date, idx) => {
    const mult = multipliers[idx];
    const dayName = days[idx % 7];
    const views = Math.round((baseViews / 14) * mult);
    const orders = Math.round((baseOrders / 14) * mult);
    const revenue = orders * avgSpend;

    return {
      date,
      dayName,
      views,
      orders,
      revenue,
    };
  });
}

